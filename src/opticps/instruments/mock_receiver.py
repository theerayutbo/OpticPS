"""Mock receiver: turns an exported waveform into a simulated capture for integration tests.

Every file it writes is marked data_source = simulated. It models no real instrument.
"""

# SPDX-License-Identifier: MIT
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from opticps.measurement.validate_export import read_waveform
from opticps.optical_channel.link import LinkConfig, transmit, watt_to_dbm
from opticps.transmitter.pulse import resample_periodic


@dataclass(frozen=True)
class MockCapture:
    """Paths written by the mock receiver."""

    metadata_path: Path
    data_path: Path


def capture_waveform(
    wave_csv: Path,
    awg_sample_rate: float,
    symbol_rate: float,
    experiment_id: str,
    probabilities: list[float],
    capture_id: str,
    run_id: str,
    split: str,
    out_dir: Path,
    link: LinkConfig,
    capture_sample_rate: float = 80e9,
    seed: int = 0,
    delay_samples: int = 1234,
    time_axis: bool = False,
) -> MockCapture:
    """Pass a waveform through the simulated link and save it in the capture format."""
    _, samples = read_waveform(wave_csv)
    wave = resample_periodic(np.array(samples), capture_sample_rate / awg_sample_rate)
    wave = np.clip(wave, -1.0, 1.0)
    rng = np.random.default_rng(seed)
    result = transmit(wave, capture_sample_rate, link, rng)
    voltage = np.roll(result.current_a, delay_samples) * 50.0
    out_dir.mkdir(parents=True, exist_ok=True)
    metadata: dict[str, Any] = {
        "schema_version": "1.0",
        "capture_id": capture_id,
        "related_transmit_experiment_id": experiment_id,
        "run_id": run_id,
        "split": split,
        "data_source": "simulated",
        "capture_timestamp": "2026-01-01T00:00:00+00:00",
        "receiver_instrument_model": "MOCK-RECEIVER (no real instrument)",
        "transmitter_instrument_model": "MOCK-AWG (no real instrument)",
        "capture_sample_rate_Sa_per_s": capture_sample_rate,
        "symbol_rate_Bd": symbol_rate,
        "receiver_bandwidth_Hz": link.receiver_bandwidth_hz,
        "fiber_length_km": link.fiber_length_km,
        "attenuation_dB": link.extra_attenuation_db,
        "optical_launch_power_dBm": watt_to_dbm(result.launch_power_w),
        "optical_received_power_dBm": watt_to_dbm(result.received_power_w),
        "oma_dBm": watt_to_dbm(result.oma_launch_w),
        "extinction_ratio_dB": result.extinction_ratio_db,
        "awg_sample_rate_Sa_per_s": awg_sample_rate,
        "electrical_amplitude_Vpp": link.drive_vpp,
        "symbol_probabilities": probabilities,
        "units": {"time": "s", "voltage": "V"},
        "calibration": None,
        "operator_notes": "Generated by the mock receiver.",
    }
    metadata_path = out_dir / f"{capture_id}.json"
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")
    data_path = out_dir / f"{capture_id}.csv"
    if time_axis:
        first = "received_time_s"
        axis = np.arange(voltage.size) / capture_sample_rate
        lines = "\n".join(f"{t:.15e},{v:.9e}" for t, v in zip(axis, voltage, strict=True))
    else:
        first = "sample_index"
        lines = "\n".join(f"{i},{v:.9e}" for i, v in enumerate(voltage))
    data_path.write_text(f"{first},received_voltage_v\n{lines}\n")
    return MockCapture(metadata_path, data_path)
